def prompt_sha256() -> str:
    import hashlib

    payload = "\n".join(
        (
            f"taxonomy={TAXONOMY_KEY}:{TAXONOMY_VERSION}",
            f"prompt={PROMPT_VERSION}",
            "Нужно классифицировать каждый предмет отдельно по его названию и контексту.",
            "Для каждой строки выбери одну наиболее подходящую категорию из 16 вариантов.",
            "Не переносить классификацию на другие строки, даже если названия совпадают.",
            "Сначала учитывать сам предмет. Контекст программы использовать при неоднозначности.",
            "Практику, НИР и итоговую аттестацию относить к категории 16.",
            "Не выводить и не придумывать отсутствующее содержание предмета.",
            "Опции Choice — коды; названия и определения этих кодов заданы в общем taxonomy state.",
            QUESTION_INSTRUCTIONS,
            *(f"{code}\t{name}\t{definition}" for code, name, definition in CATEGORIES),
        )
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
